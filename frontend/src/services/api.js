import axios from "axios";

const api = axios.create({
  baseURL: import.meta.env.VITE_API_BASE_URL || "http://127.0.0.1:8000",
  timeout: 120000,
});

api.interceptors.request.use((config) => {
  const token = sessionStorage.getItem("mentormind_access_token");
  if (token) {
    config.headers.Authorization = `Bearer ${token}`;
  }
  return config;
});

api.interceptors.response.use(
  (response) => response,
  (error) => {
    const status = error.response?.status;
    const url = error.config?.url || "";
    const isAuthRequest = url.includes("/api/auth/login") || url.includes("/api/auth/register");

    if (status === 401 && !isAuthRequest) {
      sessionStorage.removeItem("mentormind_access_token");
      sessionStorage.removeItem("mentormind_user");
      if (window.location.pathname !== "/login") {
        window.location.assign("/login");
      }
    }
    return Promise.reject(error);
  }
);

export default api;
